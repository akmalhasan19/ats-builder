const SET = new Set<string>([...ACTION_VERBS, ...EXTRA_VERBS])

/** Kalimat pasif yang lazim menggantikan kata kerja aksi di CV Indonesia/Inggris. */
const PASSIVE_OPENERS = [
  'bertugas untuk',
  'bertugas',
  'bertanggung jawab',
  'bertanggungjawab',
  'responsible for',
  'was responsible for',
  'duties included',
  'job description',
  'tugas pokok',
  'melakukan pekerjaan',
]

export function isActionVerb(word: string): boolean {
  return SET.has(stripDiacritics(word).toLowerCase())
}

export function startsWithActionVerb(text: string): boolean {
  const trimmed = text.trim()
  if (trimmed === '') return false
  return isActionVerb(trimmed.split(/\s/, 1)[0] ?? '')
}

export function startsWithPassive(text: string): boolean {
  const head = stripDiacritics(text.trim()).toLowerCase().slice(0, 24)
  return PASSIVE_OPENERS.some((opener) => head.startsWith(opener))
}
